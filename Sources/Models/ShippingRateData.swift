// MARK: - 運送会社

/// 料金を並べる3社。
enum Carrier: String, CaseIterable, Identifiable, Codable {
    case yamato
    case japanPost
    case sagawa

    var id: String { rawValue }

    /// 会社名。
    var name: String {
        switch self {
        case .yamato: return "ヤマト運輸"
        case .japanPost: return "日本郵便"
        case .sagawa: return "佐川急便"
        }
    }

    /// 便の名前。
    var service: String {
        switch self {
        case .yamato: return "宅急便"
        case .japanPost: return "ゆうパック"
        case .sagawa: return "飛脚宅配便"
        }
    }

    /// 3辺合計の上限（センチ）。
    var maxCm: Int {
        switch self {
        case .yamato: return 200
        case .japanPost: return 170
        case .sagawa: return 260
        }
    }

    /// 重さの上限（キロ）。佐川はラージサイズだけ50キロ。
    var maxKg: Double {
        switch self {
        case .yamato: return 30
        case .japanPost: return 25
        case .sagawa: return 50
        }
    }

    /// 1辺の上限（センチ）。設けていない社は nil。
    var maxSideCm: Int? {
        switch self {
        case .yamato: return 170
        case .japanPost: return nil
        case .sagawa: return nil
        }
    }

    /// 補償の上限。各社が公表する責任限度額。
    var compensation: String {
        switch self {
        case .yamato: return "補償 30万円まで"
        case .japanPost: return "補償 30万円・セキュリティで50万円"
        case .sagawa: return "補償 30万円まで"
        }
    }

    /// 運賃の条件。表の金額をどう読むか。
    var condition: String {
        switch self {
        case .yamato: return "現金決済・税込"
        case .japanPost: return "持込割引後・税込"
        case .sagawa: return "通常運賃・税込"
        }
    }
}

