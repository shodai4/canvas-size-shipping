    /// 3辺合計に当てはまる区分の位置。上限を超えていれば nil。
    static func sizeIndex(for totalCm: Int, sizes: [Int]) -> Int? {
        sizes.firstIndex { totalCm <= $0 }
    }

    /// 運賃を引く。送出できない条件なら nil。
    static func fare(carrier: Carrier,
                     origin: Prefecture,
                     destination: Prefecture,
                     totalCm: Int,
                     weightKg: Double = 0) -> Int? {
        switch carrier {
        case .yamato:
            guard let index = sizeIndex(for: totalCm, sizes: yamatoSizes) else { return nil }
            if origin == destination && origin != .okinawa {
                return yamatoLocal[index]
            }
            return yamato[origin.yamatoZone][index][destination.yamatoZone]
        case .japanPost:
            guard let index = sizeIndex(for: totalCm, sizes: postSizes) else { return nil }
            if origin == destination {
                return postLocal[Prefecture.allCases.firstIndex(of: origin) ?? 0][index]
            }
            return post[origin.postZone][index][destination.postZone]
        case .sagawa:
            guard let index = sizeIndex(for: totalCm, sizes: sagawaSizes) else { return nil }
            return sagawa[origin.sagawaZone][index][destination.sagawaZone]
        }
    }

    /// 区分のセンチ。上限を超えていれば nil。
    static func sizeCm(carrier: Carrier, totalCm: Int) -> Int? {
        switch carrier {
        case .yamato: return yamatoSizes.first { totalCm <= $0 }
        case .japanPost: return postSizes.first { totalCm <= $0 }
        case .sagawa: return sagawaSizes.first { totalCm <= $0 }
        }
    }

    /// 佐川のラージサイズか。
    static func isLarge(carrier: Carrier, sizeCm: Int) -> Bool {
        carrier == .sagawa && sagawaLargeSizes.contains(sizeCm)
    }
